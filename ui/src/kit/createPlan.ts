// A create plan (SD-013, Rule 2): a declared action whose effects are exactly one `create` of the type
// and any number of `link` effects of which one end is the created alias (the other a `ref` input or
// another alias). Every other effect shape is not a create plan. The matcher reads the wire's tagged
// shapes (effects.ts): the key is an input the form asks for, or generated.
import { shortName } from "../api/gql";
import type { ActionInfo, Effect, EffectDecl, InputSpec, ModuleInfo, Receipt } from "../api/types";
import { aliasKeyOf, declaredAlias, inputOf, isGenerated } from "./effects";

export type CreateKey = { input: string } | { generated: true };

export interface CreatePlan {
  /** The module-qualified action (`catalog.AddSolution`). */
  action: string;
  /** The qualified type the action creates. */
  type: string;
  /** An input the form asks for, or generated by the server. */
  key: CreateKey;
  /** Every input of the action, in declared order: the form asks for all of them. */
  inputs: InputSpec[];
  /** The `ref` inputs the created entity is linked to. */
  refInputs: string[];
}

/** The key of a create effect: an input of the action, or generated; nothing else is a plan. */
function keyOf(action: ActionInfo, create: EffectDecl): CreateKey | undefined {
  if (isGenerated(create.key)) return { generated: true };
  const input = inputOf(create.key);
  return input && action.inputSpecs.some((s) => s.name === input) ? { input } : undefined;
}

/** The input an end names when it is a ref input of the action, else nothing. */
const refEnd = (action: ActionInfo, end: unknown): string | undefined => {
  const name = inputOf(end);
  const spec = action.inputSpecs.find((s) => s.name === name);
  return spec?.kind === "ref" ? spec.name : undefined;
};

/**
 * Whether `link` joins the created alias to something else; its other end's ref input, `""` for
 * another alias, or undefined when the link is not of that shape.
 */
function otherEnd(action: ActionInfo, link: EffectDecl, created: string | undefined) {
  if (!created) return undefined;
  const ends = [link.source, link.target];
  const mine = ends.filter((e) => aliasKeyOf(e) === created);
  if (mine.length !== 1) return undefined;
  const other = ends.find((e) => aliasKeyOf(e) !== created);
  if (aliasKeyOf(other) !== undefined) return "";
  return refEnd(action, other);
}

/** The plan `action` gives for creating `type`, if its effects are exactly that. */
function planFor(action: ActionInfo, type: string): CreatePlan | undefined {
  const [create, ...rest] = action.effects;
  if (create?.op !== "create" || !create.type || shortName(create.type) !== shortName(type))
    return undefined;
  const key = keyOf(action, create);
  if (!key) return undefined;
  const alias = declaredAlias(create);
  const refInputs: string[] = [];
  for (const link of rest) {
    const other = link.op === "link" ? otherEnd(action, link, alias) : undefined;
    if (other === undefined) return undefined;
    if (other) refInputs.push(other);
  }
  return { action: action.name, type: create.type, key, inputs: action.inputSpecs, refInputs };
}

/** Every create plan of `type`, the one with the fewest inputs first, then by name. */
export function createPlans(module: ModuleInfo, type: string): CreatePlan[] {
  return module.actions
    .flatMap((a) => {
      const plan = planFor(a, type);
      return plan ? [plan] : [];
    })
    .sort((x, y) => x.inputs.length - y.inputs.length || x.action.localeCompare(y.action));
}

/**
 * The key of the entity a create made: the key of the validated `create` effect of the plan's type,
 * confirmed by the receipt's ref of that type. A receipt that does not carry the validated key (a
 * generated key the server settled differently) names it only when it holds exactly one such ref.
 */
export function createdKey(
  plan: CreatePlan,
  effects: readonly Effect[],
  receipt: Receipt,
): string | undefined {
  const same = (type: string) => shortName(type) === shortName(plan.type);
  const made = receipt.refs.filter((r) => same(r.type));
  const create = effects.find((e) => e.kind === "create" && same(e.ref.type));
  const key = create?.kind === "create" ? create.ref.key : undefined;
  if (key !== undefined && made.some((r) => r.key === key)) return key;
  return made.length === 1 ? made[0]?.key : undefined;
}

/** How to create an entity of `type`, or undefined where no declared action only creates it. */
export const createPlan = (module: ModuleInfo, type: string): CreatePlan | undefined =>
  createPlans(module, type)[0];
